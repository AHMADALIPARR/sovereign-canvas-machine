package SCM::Braid;
use strict;
use warnings;
use Math::BigInt;
use Exporter 'import';
our @EXPORT_OK = qw(parse_gens parse_gens_strict invariant permutation
    equivalent exact_braid_equal matrix_invariant exponent_sum word_metrics);

# Artin representation of B3 on the free group F3.
# Faithful: two words are equal in B3 iff the freely reduced images agree.
# Generator sign: +1 s1, -1 s1_inv, +2 s2, -2 s2_inv.
# Free letters: +1,+2,+3 and their inverses.

my %ACT = (
    1  => { 1 => [1, 2, -1], 2 => [1],       3 => [3] },
    -1 => { 1 => [2],        2 => [-2, 1, 2], 3 => [3] },
     2 => { 1 => [1],        2 => [2, 3, -2], 3 => [2] },
    -2 => { 1 => [1],        2 => [3],         3 => [-3, 2, 3] },
);

sub parse_gens {
    my ($s) = @_;
    my @o;
    for my $tok (split / /, $s // '') {
        if    ($tok eq 's1')     { push @o, 1 }
        elsif ($tok eq 's1_inv') { push @o, -1 }
        elsif ($tok eq 's2')     { push @o, 2 }
        elsif ($tok eq 's2_inv') { push @o, -2 }
        else                     { return }
    }
    return @o;
}

# Strict parse: undef on an invalid token, an array reference otherwise.
# The empty string is a valid word (the identity), NOT an error, so it
# must be distinguishable from a failed parse. parse_gens (above) cannot
# make that distinction, which is why equivalent() used to reject the
# identity outright, including identity == identity.
sub parse_gens_strict {
    my ($s) = @_;
    my @o;
    for my $tok (split / /, $s // '') {
        if    ($tok eq 's1')     { push @o, 1 }
        elsif ($tok eq 's1_inv') { push @o, -1 }
        elsif ($tok eq 's2')     { push @o, 2 }
        elsif ($tok eq 's2_inv') { push @o, -2 }
        else                     { return }
    }
    return \@o;
}

sub freduce {
    my @s;
    for my $g (@_) {
        if (@s && $s[-1] == -$g) { pop @s }
        else                     { push @s, $g }
    }
    return @s;
}

sub apply_word {
    my @img = ([1], [2], [3]);
    for my $g (@_) {
        my $map = $ACT{$g} or return;
        my @next;
        for my $strand (0 .. 2) {
            my @buf;
            for my $L (@{ $img[$strand] }) {
                my $piece = $map->{ abs($L) };
                if ($L > 0) { push @buf, @$piece }
                else        { push @buf, map { -$_ } reverse @$piece }
            }
            push @next, [ freduce(@buf) ];
        }
        @img = @next;
    }
    return @img;
}

sub invariant {
    my @img = apply_word(@_);
    return join ';', map { join(',', @$_) } @img;
}

sub equivalent {
    my ($a, $b) = @_;
    my $wa = ref($a) eq 'ARRAY' ? $a : parse_gens_strict($a);
    my $wb = ref($b) eq 'ARRAY' ? $b : parse_gens_strict($b);
    return 0 unless defined $wa && defined $wb;
    return invariant(@$wa) eq invariant(@$wb);
}

# Independent cross-check on the Artin invariant: the Burau representation
# at t = -1, s1 = [[1,1],[0,1]], s2 = [[1,0],[-1,1]], inverses to exact
# inverse matrices, entries in Math::BigInt so no overflow at any length.
# Matrix equality alone is NOT braid equality: the representation has a
# kernel generated by the fourth power of the full twist (identity matrix,
# exponent sum 24). exact_braid_equal therefore requires BOTH matrix
# equality and exponent-sum equality, which together are exact for B3.
my %MAT = (
    1  => [[1, 1], [0, 1]],
    -1 => [[1, -1], [0, 1]],
    2  => [[1, 0], [-1, 1]],
    -2 => [[1, 0], [1, 1]],
);

sub _mat_mul {
    my ($a, $b) = @_;
    my @c;
    for my $i (0, 1) {
        for my $j (0, 1) {
            my $s = Math::BigInt->new(0);
            for my $k (0, 1) {
                $s->badd(Math::BigInt->new($a->[$i][$k])->bmul($b->[$k][$j]));
            }
            $c[$i][$j] = $s;
        }
    }
    return \@c;
}

sub matrix_invariant {
    my @m = ([Math::BigInt->new(1), Math::BigInt->new(0)],
             [Math::BigInt->new(0), Math::BigInt->new(1)]);
    for my $g (@_) {
        my $gm = $MAT{$g} or return;
        @m = @{ _mat_mul(\@m, $gm) };
    }
    return join ',', map { $_->bstr } $m[0][0], $m[0][1], $m[1][0], $m[1][1];
}

sub exponent_sum {
    my $s = 0;
    for my $g (@_) {
        return unless exists $MAT{$g};
        $s += $g > 0 ? 1 : -1;
    }
    return $s;
}

sub exact_braid_equal {
    my ($a, $b) = @_;
    my $wa = ref($a) eq 'ARRAY' ? $a : parse_gens_strict($a);
    my $wb = ref($b) eq 'ARRAY' ? $b : parse_gens_strict($b);
    return 0 unless defined $wa && defined $wb;
    return matrix_invariant(@$wa) eq matrix_invariant(@$wb)
        && exponent_sum(@$wa) == exponent_sum(@$wb);
}

# Word metrics. Length, exponent sum, syllable count (maximal runs of
# one generator ignoring sign), and the permutation image, for the
# optimizer and for diagnostics. All return undef on an invalid word.
sub word_metrics {
    my ($w) = @_;
    my $gens = ref($w) eq 'ARRAY' ? $w : parse_gens_strict($w);
    return unless defined $gens;
    my $syllables = 0;
    my $prev_abs = 0;
    for my $g (@$gens) {
        my $a = abs($g);
        $syllables++ if $a != $prev_abs;
        $prev_abs = $a;
    }
    return {
        length       => scalar @$gens,
        exponent_sum => exponent_sum(@$gens),
        syllables    => $syllables,
        permutation  => join(',', permutation(@$gens)),
        matrix       => matrix_invariant(@$gens),
        artin        => invariant(@$gens),
    };
}

sub permutation {
    my @p = (0, 1, 2);
    for my $g (@_) {
        my $i = (abs($g) == 1) ? 0 : 1;
        @p[ $i, $i + 1 ] = @p[ $i + 1, $i ];
    }
    return @p;
}

1;
